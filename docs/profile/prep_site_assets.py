#!/usr/bin/env python3
"""Website v1.0 assets from the company-profile asset set (handover/profile/assets, built by prep_assets.py,
prep_posts.py and prep_tamm.py): work by industry, Tamm, the client-journey stock, case pictures and the hero mosaic.
Writes WebP files to site/public/v1/ and a size manifest to site/src/data/v1assets.ts (width/height for every <img>).
Usage (repo root): python3 docs/profile/prep_site_assets.py"""
import ast, json, os
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../..'))
A = os.path.join(ROOT, 'handover/profile/assets'); OUT = os.path.join(ROOT, 'site/public/v1'); os.makedirs(OUT, exist_ok=True)
SRC = open(os.path.join(os.path.dirname(__file__), 'build_profile_v2.py'), encoding='utf-8').read(); D = {}
for n in ast.walk(ast.parse(SRC)):
    if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name):
        try: D[n.targets[0].id] = ast.literal_eval(n.value)
        except Exception: pass

jobs = {}   # name → max px
for m in D['mosaic']: jobs[m] = 720
for w in D['WORK']:
    for im in w[4]: jobs[im] = 1400 if im.startswith(('alto4k', 'sp_', 'cp_')) else 640
# the eight journey pictures (stk_*) and the case pictures are owner-generated photography (2026-11-26), placed by hand
# tamm_capcard, tamm_welcomecard, tamm_404 and hero_tamm_* are owner-generated key visuals (2026-11-26), placed by hand: never overwritten here
jobs['tamm_hero'] = 900

import re as _re
manifest = {}
_old = os.path.join(ROOT, 'site/src/data/v1assets.ts')
if os.path.exists(_old):
    for k, w, h in _re.findall(r'"(\w+)": \[\s*(\d+),\s*(\d+)\s*\]', open(_old, encoding='utf-8').read()): manifest[k] = [int(w), int(h)]
for name, mx in jobs.items():
    p = os.path.join(A, name + '.png') if os.path.exists(os.path.join(A, name + '.png')) else os.path.join(A, name + '.jpg')
    im = Image.open(p); im = im.convert('RGBA' if im.mode in ('RGBA', 'LA') else 'RGB'); im.thumbnail((mx, mx), Image.LANCZOS)
    im.save(os.path.join(OUT, name + '.webp'), 'WEBP', quality=80, method=6)
    manifest[name] = [im.width, im.height]
ts = ('// Generated by docs/profile/prep_site_assets.py: size of every image in /public/v1 (width, height).\n'
      'export const V1: Record<string, [number, number]> = ' + json.dumps(manifest, indent=1) + ';\n'
      'export const v1src = (n: string) => `/v1/${n}.webp`;\n')
open(os.path.join(ROOT, 'site/src/data/v1assets.ts'), 'w', encoding='utf-8').write(ts)
total = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
print(len(manifest), 'images', round(total / 1e6, 1), 'MB')
